import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const focus = fs.readFileSync('crates/inputforge-app/assets/menu_focus.js', 'utf8');
const items = [0,1,2].map(i => ({disabled: i===1, aria: i===1?'true':null, focus(){document.activeElement=this;}, getAttribute(){return this.aria;}}));
const document = {activeElement: null, getElementById(id){return id==='menu'?{querySelectorAll:()=>items}:null;}};
const context = vm.createContext({document});
const walk=(action)=>vm.runInContext(`(${focus})('menu', '${action}')`,context);
walk('first'); assert.equal(document.activeElement,items[0]);
walk('down'); assert.equal(document.activeElement,items[2]);
walk('down'); assert.equal(document.activeElement,items[0]);
walk('up'); assert.equal(document.activeElement,items[2]);
walk('first'); walk('last'); assert.equal(document.activeElement,items[2]);
items.splice(2,1); walk('down'); assert.equal(document.activeElement,items[0]);
items.push({disabled:false,getAttribute:()=> 'true',focus(){throw new Error('aria-disabled items cannot take focus');}});
walk('last'); assert.equal(document.activeElement,items[0]);
vm.runInContext(`(${focus})('removed', 'first')`,context);
items.splice(0); walk('first');
console.log('menu focus skips disabled, wraps and tolerates removed focus targets');
const clickAway = fs.readFileSync('crates/inputforge-app/assets/click_away.js','utf8');
const calls=[];
const listeners=new Set(); let removals=0;
const target={contains:n=>n==='nested'}, exclude={contains:n=>n==='trigger-child'};
const cawDocument={getElementById:id=>({target,exclude})[id]??null,
    addEventListener:(type,fn)=>listeners.add(fn), removeEventListener:(type,fn)=>{assert(listeners.delete(fn));removals++;}};
const window={}; const waiters=[];
const listenerContext=vm.createContext({document:cawDocument,window,dioxus:{send:value=>calls.push(value),recv:()=>new Promise(resolve=>waiters.push(resolve))}});
const install=(key)=>vm.runInContext(`{${clickAway.replace('__KEY__',JSON.stringify(key)).replace('__TARGET__','"target"').replace('__EXCLUDE__','"exclude"')}}`,listenerContext);
install('one'); const fire=e=>[...listeners].forEach(fn=>fn(e));
fire({target:'nested'}); fire({target:'trigger-child'});
fire({target:'outside',composedPath:()=>[target]}); fire({target:'outside',composedPath:()=>[exclude]});
assert.equal(calls.length,0);
fire({target:'outside',composedPath:()=>[]}); assert.deepEqual(calls,['away']);
window.one(); window.one(); assert.equal(removals,1); assert.equal(listeners.size,0);
install('two'); fire({target:'outside'}); assert.equal(calls.length,2);
window.two(); assert.equal(removals,2);
waiters.forEach(resolve=>resolve('__shutdown__')); await Promise.resolve();
assert.equal(removals,2); assert.equal(listeners.size,0);
// Cancel listeners always suppress native closure: only Rust acknowledgement closes.
const dialogScript=fs.readFileSync('crates/inputforge-app/assets/dialog_cancel.js','utf8');
const cancels=new Set();let cancelRemovals=0;
const dialog={addEventListener:(type,fn)=>cancels.add(fn),removeEventListener:(type,fn)=>{assert(cancels.delete(fn));cancelRemovals++;}};
const dialogContext=vm.createContext({window:{},document:{getElementById:()=>dialog}});
const attach=()=>vm.runInContext(`{${dialogScript.replace('__KEY__','"dialog"').replace('__ID__','"id"')}}`,dialogContext);
attach(); let prevented=0; [...cancels][0]({preventDefault(){prevented++;}}); assert.equal(prevented,1);
vm.runInContext('window.dialog(); window.dialog();',dialogContext); assert.equal(cancelRemovals,1);
attach(); vm.runInContext('window.dialog();',dialogContext); assert.equal(cancelRemovals,2); assert.equal(cancels.size,0);
console.log('click-away nested/excluded/shadow paths, exactly-once cleanup/remount, controlled cancel: passed');
